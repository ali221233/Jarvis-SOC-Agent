// ============================================================
// Jarvis SOC — PDF Report Generator
// Professional SOC incident report using PDFKit.
// Dark navy header, teal accents, severity badges.
// ============================================================

const PDFDocument = require('pdfkit');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { getSessionActions } = require('./logger');
const cvssScorer = require('./cvss-scorer');

const DATA_DIR = path.join(__dirname, '..', 'data');
const PDF_PATH = path.join(DATA_DIR, 'session_report.pdf');
const MD_PATH = path.join(DATA_DIR, 'session_report.md');

// Colors
const NAVY = '#0B1F33';
const TEAL = '#0FA3A3';
const WHITE = '#FFFFFF';
const LIGHT_GRAY = '#94A3B8';
const DARK_BG = '#1a1a2e';

const SEVERITY_COLORS = {
  CRITICAL: '#DC2626',
  HIGH: '#EA580C',
  MEDIUM: '#CA8A04',
  LOW: '#2563EB',
  INFO: '#6B7280',
};

/**
 * Generate both PDF and Markdown reports.
 */
function generatePdfReport(sessionId) {
  const actions = getSessionActions();

  // Gather SOC data
  let alerts = [], openAlerts = [], closedAlerts = [];
  let mitreSummary = { tactics: {}, totalTechniques: 0, totalHits: 0 };
  let enrichmentHistory = [];

  try {
    const socAlerts = require('./tools/soc-alerts');
    openAlerts = socAlerts.getOpenAlerts();
    closedAlerts = socAlerts.getClosedAlerts();
    alerts = [...openAlerts, ...closedAlerts];
  } catch {}

  try {
    const socMitre = require('./tools/soc-mitre');
    mitreSummary = socMitre.getSessionHits() || mitreSummary;
  } catch {}

  try {
    const socThreatIntel = require('./tools/soc-threat-intel');
    enrichmentHistory = socThreatIntel.getEnrichmentHistory() || [];
  } catch {}

  // Calculate risk score
  const { riskScore } = cvssScorer.calculateRiskFromAlerts(openAlerts);
  let riskPosture = 'LOW';
  if (riskScore >= 75) riskPosture = 'CRITICAL';
  else if (riskScore >= 50) riskPosture = 'HIGH';
  else if (riskScore >= 25) riskPosture = 'MEDIUM';

  const sessionStart = actions.length > 0 ? actions[0].timestamp : new Date().toISOString();
  const sessionEnd = new Date().toISOString();
  const timestamp = new Date().toISOString();
  const hashPrefix = crypto.createHash('sha256').update(timestamp + (sessionId || '')).digest('hex').substring(0, 8);
  const reportId = `RPT-${timestamp.slice(0, 10)}-${hashPrefix}`;

  // ---- Generate PDF ----
  if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });

  const doc = new PDFDocument({
    size: 'A4',
    margins: { top: 50, bottom: 50, left: 50, right: 50 },
    info: {
      Title: `Jarvis SOC Report ${reportId}`,
      Author: 'Jarvis Autonomous SOC Agent',
      Subject: 'Security Incident Report',
    },
  });

  const stream = fs.createWriteStream(PDF_PATH);
  doc.pipe(stream);

  let pageNum = 0;

  // Page footer handler
  doc.on('pageAdded', () => {
    pageNum++;
    addFooter(doc, pageNum, reportId);
  });

  // ---- COVER PAGE ----
  pageNum = 1;
  doc.rect(0, 0, doc.page.width, doc.page.height).fill(NAVY);

  // Title
  doc.fontSize(36).fillColor(WHITE).font('Helvetica-Bold');
  doc.text('JARVIS SOC', 50, 180, { align: 'center' });
  doc.fontSize(24).text('INCIDENT REPORT', 50, 230, { align: 'center' });

  // Teal line
  doc.moveTo(150, 275).lineTo(445, 275).strokeColor(TEAL).lineWidth(3).stroke();

  // Report details
  doc.fontSize(12).font('Helvetica').fillColor(LIGHT_GRAY);
  doc.text(`Report ID: ${reportId}`, 50, 310, { align: 'center' });
  doc.text('Prepared for: Boss', 50, 330, { align: 'center' });
  doc.text(`Session: ${sessionStart.slice(0, 19)} → ${sessionEnd.slice(0, 19)}`, 50, 350, { align: 'center' });
  doc.text('Classification: Confidential', 50, 370, { align: 'center' });

  doc.fontSize(10).fillColor('#475569');
  doc.text('Generated by Jarvis Autonomous SOC Agent', 50, 700, { align: 'center' });

  addFooter(doc, pageNum, reportId);

  // ---- EXECUTIVE SUMMARY ----
  doc.addPage();
  addHeader(doc, 'EXECUTIVE SUMMARY');

  doc.fontSize(11).font('Helvetica').fillColor('#1e293b');
  doc.text(`This report summarizes ${actions.length} security actions performed during the session. ` +
    `${openAlerts.length} alert(s) remain open, ${closedAlerts.length} resolved. ` +
    `Final risk score: ${riskScore}/100 (${riskPosture}). CVSS v3.1 methodology applied.`, {
    lineGap: 4, width: 495,
  });
  doc.moveDown();

  // Severity breakdown table
  addSectionTitle(doc, 'Findings by Severity');
  const sevCounts = { CRITICAL: 0, HIGH: 0, MEDIUM: 0, LOW: 0, INFO: 0 };
  for (const a of alerts) { sevCounts[a.severity] = (sevCounts[a.severity] || 0) + 1; }

  let tableY = doc.y;
  for (const [sev, count] of Object.entries(sevCounts)) {
    const color = SEVERITY_COLORS[sev] || '#6B7280';
    doc.fontSize(10).font('Helvetica-Bold').fillColor(color);
    doc.text(sev, 60, tableY, { continued: false });
    doc.font('Helvetica').fillColor('#1e293b');
    doc.text(String(count), 160, tableY);
    tableY += 18;
  }
  doc.y = tableY + 10;

  // Risk score
  addSectionTitle(doc, 'Risk Posture');
  const riskColor = riskScore >= 75 ? SEVERITY_COLORS.CRITICAL :
    riskScore >= 50 ? SEVERITY_COLORS.HIGH :
    riskScore >= 25 ? SEVERITY_COLORS.MEDIUM : '#22C55E';

  doc.fontSize(28).font('Helvetica-Bold').fillColor(riskColor);
  doc.text(`${riskScore}`, 60, doc.y);
  doc.fontSize(12).font('Helvetica').fillColor('#64748b');
  doc.text(`/ 100  —  ${riskPosture}  (CVSS v3.1 based)`, 105, doc.y - 18);
  doc.moveDown(2);

  // ---- OPEN INCIDENTS ----
  if (openAlerts.length > 0) {
    doc.addPage();
    addHeader(doc, 'OPEN INCIDENTS');

    for (const alert of openAlerts) {
      const cvss = cvssScorer.getCvssForAlert(alert.severity);
      addAlertBlock(doc, alert, cvss);
    }
  }

  // ---- CLOSED INCIDENTS ----
  if (closedAlerts.length > 0) {
    doc.addPage();
    addHeader(doc, 'RESOLVED INCIDENTS');

    for (const alert of closedAlerts) {
      const cvss = cvssScorer.getCvssForAlert(alert.severity);
      addAlertBlock(doc, alert, cvss);
    }
  }

  // ---- THREAT INTELLIGENCE ----
  if (enrichmentHistory.length > 0) {
    doc.addPage();
    addHeader(doc, 'THREAT INTELLIGENCE FINDINGS');

    for (const entry of enrichmentHistory.slice(0, 20)) {
      doc.fontSize(10).font('Helvetica-Bold').fillColor(TEAL);
      doc.text(`${entry.type || 'IP'}: ${entry.indicator || entry.value || 'N/A'}`, 60);
      doc.font('Helvetica').fillColor('#475569');
      doc.text(`Score: ${entry.score || 'N/A'} | Source: ${entry.source || 'N/A'}`, 60);
      doc.moveDown(0.5);

      if (doc.y > 700) doc.addPage();
    }
  }

  // ---- MITRE ATT&CK ----
  if (mitreSummary && mitreSummary.totalTechniques > 0) {
    doc.addPage();
    addHeader(doc, 'MITRE ATT&CK COVERAGE');

    doc.fontSize(11).fillColor('#1e293b').font('Helvetica');
    doc.text(`${mitreSummary.totalTechniques} technique(s) triggered, ${mitreSummary.totalHits} total hits.`);
    doc.moveDown();

    if (mitreSummary.tactics) {
      for (const [tactic, techniques] of Object.entries(mitreSummary.tactics)) {
        doc.fontSize(10).font('Helvetica-Bold').fillColor(TEAL);
        doc.text(tactic.toUpperCase(), 60);
        doc.font('Helvetica').fillColor('#475569');
        if (Array.isArray(techniques)) {
          for (const t of techniques) {
            doc.text(`  • ${t.id || t.name || t}: ${t.count || 1} hit(s)`, 70);
          }
        }
        doc.moveDown(0.3);
      }
    }
  }

  // ---- TIMELINE ----
  doc.addPage();
  addHeader(doc, 'TIMELINE OF ACTIONS');

  for (const action of actions.slice(-50)) {
    const time = action.timestamp ? action.timestamp.slice(11, 19) : '??:??:??';
    const tierLabel = action.source === 'background_monitor' ? '[BG]' : `[T${action.tier || 1}]`;
    const tierColor = action.source === 'background_monitor' ? '#6B7280' :
      action.tier === 3 ? SEVERITY_COLORS.CRITICAL :
      action.tier === 2 ? SEVERITY_COLORS.MEDIUM : TEAL;

    doc.fontSize(9).font('Courier').fillColor(tierColor);
    doc.text(`${time} ${tierLabel}`, 50, doc.y, { continued: true, width: 120 });
    doc.fillColor('#1e293b').font('Helvetica');
    doc.text(` ${action.summary || action.tool || 'Action'}`, { width: 380 });

    if (doc.y > 720) { doc.addPage(); addHeader(doc, 'TIMELINE (continued)'); }
  }

  // ---- RISK POSTURE FINAL ----
  doc.addPage();
  addHeader(doc, 'RISK POSTURE ASSESSMENT');

  doc.fontSize(11).fillColor('#1e293b').font('Helvetica');
  doc.text(`Final CVSS-based risk score: ${riskScore}/100 (${riskPosture})`, 60);
  doc.moveDown();
  doc.text('Scoring methodology: Each finding is assigned a CVSS v3.1 vector string. ' +
    'The base score is calculated using the official FIRST.org formula. ' +
    'Scores are then mapped to risk point contributions and summed, capped at 100.', {
    lineGap: 4, width: 495,
  });

  // ---- INTEGRITY ----
  doc.moveDown(3);
  addSectionTitle(doc, 'Integrity Verification');

  const reportContent = `RPT:${reportId}|RISK:${riskScore}|ACTIONS:${actions.length}|ALERTS:${alerts.length}|TIME:${timestamp}`;
  const sha256 = crypto.createHash('sha256').update(reportContent).digest('hex');

  doc.fontSize(9).font('Courier').fillColor('#475569');
  doc.text(`SHA-256: ${sha256}`, 60);
  doc.text(`Signed at: ${timestamp}`, 60);
  doc.moveDown();
  doc.fontSize(10).font('Helvetica').fillColor(TEAL);
  doc.text('Generated by Jarvis Autonomous SOC Agent', 60);

  // ---- FINALIZE ----
  doc.end();

  return new Promise((resolve, reject) => {
    stream.on('finish', () => {
      const fileSize = fs.statSync(PDF_PATH).size;
      console.log(`  [PDF] Report saved: ${PDF_PATH} (${(fileSize / 1024).toFixed(1)} KB)`);

      resolve({
        pdfPath: PDF_PATH,
        mdPath: MD_PATH,
        reportId,
        riskScore,
        riskPosture,
        sha256,
        fileSize,
        message: `Report generated, Boss. PDF saved and ready. SHA-256: ${sha256}`,
      });
    });
    stream.on('error', reject);
  });
}

// ---- Helper Functions ----

function addHeader(doc, title) {
  doc.rect(0, 0, doc.page.width, 70).fill(NAVY);
  doc.moveTo(50, 70).lineTo(545, 70).strokeColor(TEAL).lineWidth(2).stroke();
  doc.fontSize(16).font('Helvetica-Bold').fillColor(WHITE);
  doc.text(title, 50, 25, { width: 495 });
  doc.y = 90;
}

function addFooter(doc, pageNum, reportId) {
  doc.fontSize(8).font('Helvetica').fillColor('#475569');
  doc.text(`${reportId}`, 50, doc.page.height - 40);
  doc.text(`Page ${pageNum}`, doc.page.width - 100, doc.page.height - 40);
}

function addSectionTitle(doc, title) {
  doc.fontSize(13).font('Helvetica-Bold').fillColor(TEAL);
  doc.text(title, 50);
  doc.moveTo(50, doc.y).lineTo(250, doc.y).strokeColor(TEAL).lineWidth(1).stroke();
  doc.moveDown(0.5);
}

function addAlertBlock(doc, alert, cvss) {
  const color = SEVERITY_COLORS[alert.severity] || '#6B7280';

  // Severity badge
  const badgeY = doc.y;
  doc.rect(55, badgeY, 70, 18).fillAndStroke(color, color);
  doc.fontSize(9).font('Helvetica-Bold').fillColor(WHITE);
  doc.text(alert.severity, 60, badgeY + 4, { width: 60, align: 'center' });

  // CVSS badge
  doc.rect(130, badgeY, 55, 18).fillAndStroke('#334155', '#334155');
  doc.text(`CVSS ${cvss.score}`, 133, badgeY + 4, { width: 50, align: 'center' });

  // Alert title
  doc.fontSize(11).font('Helvetica-Bold').fillColor('#1e293b');
  doc.text(alert.title || 'Alert', 195, badgeY + 2, { width: 350 });

  doc.y = badgeY + 24;
  doc.fontSize(9).font('Helvetica').fillColor('#64748b');
  doc.text(`ID: ${alert.id} | Source: ${alert.source || 'N/A'} | Vector: ${cvss.vector}`, 60);

  if (alert.details) {
    doc.fontSize(9).fillColor('#475569');
    doc.text(alert.details.substring(0, 200), 60, doc.y + 2, { width: 480 });
  }

  if (alert.resolution) {
    doc.fontSize(9).fillColor('#22C55E');
    doc.text(`Resolution: ${alert.resolution}`, 60);
  }

  doc.moveDown();

  if (doc.y > 700) doc.addPage();
}

module.exports = { generatePdfReport };
